const originals = new WeakMap(),
  attributes = new WeakMap();
const normalize = (s) => s.replace(/\s+/g, " ").trim();
export const getLanguage = () => language;
export function t(text) {
  return language === "es" ? es[normalize(text)] || text : text;
}
export function translate(root = document.body) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      return node.parentElement?.closest(
        "script,style,.material-symbols-outlined,[data-no-translate]",
      )
        ? NodeFilter.FILTER_REJECT
        : NodeFilter.FILTER_ACCEPT;
    },
  });
  let n;
  while ((n = walker.nextNode())) {
    if (!originals.has(n)) originals.set(n, n.textContent);
    const original = originals.get(n),
      key = normalize(original);
    if (key && es[key])
      n.textContent =
        language === "es" ? original.replace(key, es[key]) : original;
  }
  root.querySelectorAll("[placeholder],[aria-label],[title]").forEach((el) => {
    if (!attributes.has(el))
      attributes.set(
        el,
        Object.fromEntries(
          ["placeholder", "aria-label", "title"]
            .filter((a) => el.hasAttribute(a))
            .map((a) => [a, el.getAttribute(a)]),
        ),
      );
    for (const [a, value] of Object.entries(attributes.get(el)))
      el.setAttribute(a, t(value));
  });
  document.documentElement.lang = language;
  document
    .querySelectorAll("[data-lang]")
    .forEach((b) =>
      b.setAttribute("aria-pressed", String(b.dataset.lang === language)),
    );
  const page = document.body.dataset.page;
  document.title = `${t({ index: "Home", resources: "Resource Directory", events: "Events", about: "About Us", contact: "Contact" }[page])} | CommunityConnect`;
}
export function setLanguage(next) {
  if (!["en", "es"].includes(next)) return;
  language = next;
  try {
    localStorage.setItem("communityconnect.language", next);
  } catch {}
  translate();
  document.dispatchEvent(new CustomEvent("languagechange", { detail: next }));
}
export function dateLabel(date) {
  return new Intl.DateTimeFormat(language === "es" ? "es-US" : "en-US", {
    weekday: "short",
    month: "long",
    day: "numeric",
    year: "numeric",
    timeZone: "UTC",
  }).format(new Date(`${date}T12:00:00Z`));
}
export function initLanguage() {
  translate();
  document
    .querySelectorAll("[data-lang]")
    .forEach((b) =>
      b.addEventListener("click", () => setLanguage(b.dataset.lang)),
    );
}
